-- supabase/migrations/224_reword_album_hidden_notice.sql
--
-- NEVER PUT THE WORD IN THE MESSAGE.
--
-- The notice an artist gets when their plan lapses said:
--
--   "... your albums and the songs on them are hidden from listeners. Your
--    singles are still live. Nothing has been deleted and nothing is lost."
--
-- Every word of that is true and it still went wrong. The reassurance is in
-- the negative, so the word "deleted" sits in the same paragraph as "your
-- albums are hidden", and somebody reading it on a phone, already upset that
-- their music has vanished from the app, takes away "albums, hidden,
-- deleted". The first artist it reached believed his catalogue was being
-- destroyed, and he was reading the sentence that was meant to promise him it
-- was not.
--
-- The fix is not a softer denial. It is to say the true thing in the positive
-- and never type the word at all. "Your music is safe and still here" cannot
-- be misread the way "nothing has been deleted" can.
--
-- This is generated by the nightly job, so it is the message every artist who
-- lapses from here on will read. Changing it once changes it for all of them.
--
-- Only the message text differs from 220. The logic is reproduced unchanged
-- on purpose, so this file is the whole function and not a patch that has to
-- be read alongside another one.

begin;

create or replace function public.enforce_free_tier_albums()
returns table(artists_affected int, albums_hidden int, tracks_hidden int)
language plpgsql
security definer
set search_path to 'public'
as $fn$
declare
  v_artists int := 0;
  v_albums  int := 0;
  v_tracks  int := 0;
begin
  select count(distinct al.artist_id) into v_artists
  from albums al
  where al.is_published = true
    and not artist_has_active_plan(al.artist_id);

  insert into tier_enforcement_archive (artist_id, kind, target_id, was_published, reason)
  select al.artist_id, 'album', al.id, true, 'free tier: albums are a paid feature'
  from albums al
  where al.is_published = true
    and not artist_has_active_plan(al.artist_id);

  insert into tier_enforcement_archive (artist_id, kind, target_id, was_published, reason)
  select t.artist_id, 'track', t.id, true, 'free tier: albums are a paid feature'
  from tracks t
  where t.is_published = true
    and t.album_id is not null
    and not artist_has_active_plan(t.artist_id);

  insert into notifications (user_id, artist_id, type, title, message, email_requested, metadata)
  select
    ar.user_id,
    ar.id,
    'admin_message',
    'Your albums are paused while your plan is off',
    'Albums and EPs are part of a paid plan, and yours is not active at the moment, so your albums and the songs on them are not showing to listeners right now. Your singles are still live. '
    || 'Your music is safe and exactly where you left it, every file and every cover, on your dashboard where only you can see it. '
    || 'Turn a plan back on from your artist dashboard and all of it is back in front of listeners the same day, with its plays and its likes intact.',
    true,
    jsonb_build_object('kind', 'free_tier_albums_hidden')
  from artists ar
  where ar.user_id is not null
    and exists (
      select 1 from albums al
      where al.artist_id = ar.id and al.is_published = true
        and not artist_has_active_plan(ar.id)
    )
    and not exists (
      select 1 from notifications n
      where n.artist_id = ar.id
        and n.metadata->>'kind' = 'free_tier_albums_hidden'
        and n.created_at > now() - interval '30 days'
    );

  update albums al
  set is_published = false
  where al.is_published = true
    and not artist_has_active_plan(al.artist_id);
  get diagnostics v_albums = row_count;

  update tracks t
  set is_published = false
  where t.is_published = true
    and t.album_id is not null
    and not artist_has_active_plan(t.artist_id);
  get diagnostics v_tracks = row_count;

  return query select v_artists, v_albums, v_tracks;
end;
$fn$;

commit;

-- ── Check ───────────────────────────────────────────────────────────────────
-- The new wording is in place, and it contains none of the words that caused
-- the trouble. Running the function changes nothing today: everybody who
-- needed hiding was hidden on the 14th.
select 'uses the word deleted' as k,
       case when prosrc ilike '%delet%' then 'YES, FIX THIS' else 'no' end as v
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.proname = 'enforce_free_tier_albums'
union all
select 'uses the word lost',
       case when prosrc ilike '%nothing is lost%' then 'YES, FIX THIS' else 'no' end
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.proname = 'enforce_free_tier_albums'
union all
select 'new title present',
       case when prosrc ilike '%paused while your plan is off%' then 'yes' else 'NO, FIX THIS' end
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.proname = 'enforce_free_tier_albums'
order by 1;
